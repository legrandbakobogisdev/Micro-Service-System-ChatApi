#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

/**
 * Script to generate the complete marketplace platform structure
 */

const ROOT_DIR = path.join(__dirname, '..');

// Define all services
const SERVICES = [
  'auth-service',
  'subscription-service',
  'payment-service',
  'notification-service',
  'analytics-service',
  'support-service',
  'media-service',
  'chat-service',
  'api-gateway'
];

// Service subdirectories structure
const SERVICE_SUBDIRS = [
  'src',
  'src/config',
  'src/controllers',
  'src/models',
  'src/routes',
  'src/services',
  'src/middlewares',
  'src/utils'
];

// Shared directory structure
const SHARED_STRUCTURE = {
  'utils': [],
  'kafka-config': [],
  'database': ['migrations', 'seeds']
};

// Infrastructure structure
const INFRASTRUCTURE_STRUCTURE = {
  'nginx': [],
  'monitoring': ['prometheus'],
  'database': []
};

/**
 * Create directory if it doesn't exist
 */
function ensureDir(dirPath) {
  if (!fs.existsSync(dirPath)) {
    fs.mkdirSync(dirPath, { recursive: true });
    console.log(`✓ Created: ${path.relative(ROOT_DIR, dirPath)}`);
    return true;
  }
  return false;
}

/**
 * Create services directory structure
 */
function createServicesStructure() {
  console.log('\n📦 Creating services structure...\n');
  
  const servicesDir = path.join(ROOT_DIR, 'services');
  ensureDir(servicesDir);
  
  SERVICES.forEach(service => {
    const serviceDir = path.join(servicesDir, service);
    ensureDir(serviceDir);
    
    // Create subdirectories for each service
    SERVICE_SUBDIRS.forEach(subdir => {
      ensureDir(path.join(serviceDir, subdir));
    });
    
    console.log(`  ✓ ${service} structure created`);
  });
}

/**
 * Create shared directory structure
 */
function createSharedStructure() {
  console.log('\n🔧 Creating shared utilities structure...\n');
  
  const sharedDir = path.join(ROOT_DIR, 'shared');
  ensureDir(sharedDir);
  
  Object.entries(SHARED_STRUCTURE).forEach(([dir, subdirs]) => {
    const dirPath = path.join(sharedDir, dir);
    ensureDir(dirPath);
    
    subdirs.forEach(subdir => {
      ensureDir(path.join(dirPath, subdir));
    });
    
    console.log(`  ✓ shared/${dir} created`);
  });
}

/**
 * Create infrastructure directory structure
 */
function createInfrastructureStructure() {
  console.log('\n🏗️  Creating infrastructure structure...\n');
  
  const infraDir = path.join(ROOT_DIR, 'infrastructure');
  ensureDir(infraDir);
  
  Object.entries(INFRASTRUCTURE_STRUCTURE).forEach(([dir, subdirs]) => {
    const dirPath = path.join(infraDir, dir);
    ensureDir(dirPath);
    
    subdirs.forEach(subdir => {
      ensureDir(path.join(dirPath, subdir));
    });
    
    console.log(`  ✓ infrastructure/${dir} created`);
  });
}

/**
 * Create scripts directory
 */
function createScriptsStructure() {
  console.log('\n📜 Creating scripts directory...\n');
  
  const scriptsDir = path.join(ROOT_DIR, 'scripts');
  ensureDir(scriptsDir);
  console.log(`  ✓ scripts directory ready`);
}

/**
 * Create root-level placeholder files
 */
function createPlaceholderFiles() {
  console.log('\n📄 Creating placeholder files...\n');
  
  const files = [
    '.gitignore',
    '.dockerignore',
    'README.md',
    'API.md',
    'DOCKER.md',
    'KAFKA.md',
    'INSTALLATION_CHECKLIST.md'
  ];
  
  files.forEach(file => {
    const filePath = path.join(ROOT_DIR, file);
    if (!fs.existsSync(filePath)) {
      fs.writeFileSync(filePath, `# ${file}\n\nGenerated by create-structure.js\n`);
      console.log(`  ✓ Created ${file}`);
    }
  });
}

/**
 * Generate structure summary
 */
function generateSummary() {
  console.log('\n' + '='.repeat(60));
  console.log('📊 STRUCTURE GENERATION SUMMARY');
  console.log('='.repeat(60));
  
  const counts = {
    services: SERVICES.length,
    sharedDirs: Object.keys(SHARED_STRUCTURE).length,
    infraDirs: Object.keys(INFRASTRUCTURE_STRUCTURE).length
  };
  
  console.log(`\n✓ ${counts.services} microservices`);
  console.log(`✓ ${counts.sharedDirs} shared modules`);
  console.log(`✓ ${counts.infraDirs} infrastructure components`);
  console.log(`✓ Root configuration files`);
  
  console.log('\n' + '='.repeat(60));
  console.log('✅ Project structure created successfully!');
  console.log('='.repeat(60));
  
  console.log('\n📝 Next steps:');
  console.log('  1. Run: npm run generate:secrets');
  console.log('  2. Run: npm run setup:env');
  console.log('  3. Run: npm run install:all');
  console.log('  4. Run: npm run docker:dev\n');
}

/**
 * Main execution
 */
function main() {
  console.log('\n' + '='.repeat(60));
  console.log('🚀 MARKETPLACE PLATFORM - STRUCTURE GENERATOR');
  console.log('='.repeat(60));
  
  try {
    createScriptsStructure();
    createServicesStructure();
    createSharedStructure();
    createInfrastructureStructure();
    createPlaceholderFiles();
    generateSummary();
  } catch (error) {
    console.error('\n❌ Error creating structure:', error.message);
    process.exit(1);
  }
}

// Run if called directly
if (require.main === module) {
  main();
}

module.exports = { main };
